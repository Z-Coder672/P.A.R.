// Root CA trust anchors for par.zimmzimm.com (WiFiClientSecure::setCACert).
//
// The site is behind a Cloudflare reverse proxy, so the cert the device sees is
// a Cloudflare Universal SSL edge cert -- NOT a cert we control. Cloudflare
// rotates Universal SSL across THREE CAs (Let's Encrypt, Google Trust Services,
// SSL.com) and per their docs may switch CA on any renewal WITHOUT NOTICE.
//
// Pinning only today's CA (GTS) would work for months and then brick every
// HTTPS poll on a silent renewal. So we anchor all three CAs, both algorithms:
//
//   GTS Root R1   (RSA)   Google Trust Services   exp 2036-06-22
//   GTS Root R4   (ECDSA) Google Trust Services   exp 2036-06-22  <- live chain today
//   ISRG Root X1  (RSA)   Let's Encrypt           exp 2035-06-04
//   ISRG Root X2  (ECDSA) Let's Encrypt           exp 2040-09-17
//   SSL.com TLS ECC Root CA 2022                  exp 2046-08-19
//   SSL.com TLS RSA Root CA 2022                  exp 2046-08-19
//
// Earliest expiry is 2035, so this needs no maintenance for a decade. Cost is
// ~8 KB of the 16 MB flash. We pin ROOTS, not the leaf, so Cloudflare's ~90-day
// leaf rotation needs no firmware change.
//
// Live chain at time of writing:
//   CN=zimmzimm.com (SAN zimmzimm.com, *.zimmzimm.com) -> GTS WE1 -> GTS Root R4
// Verified end-to-end with hostname checking:
//   openssl s_client -servername par.zimmzimm.com -connect par.zimmzimm.com:443 \
//     -CAfile bundle.pem -verify_hostname par.zimmzimm.com    => Verification: OK
//
// If TLS ever starts failing on every poll, re-run that command: a 4th CA would
// mean Cloudflare added an issuer and this bundle needs another root.
